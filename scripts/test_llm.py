import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from dotenv import load_dotenv
load_dotenv()

from backend.llm_advisor import generate_clinical_report, _build_client, _detect_provider

print("=" * 55)
print("  MedInsight AI — LLM API Test")
print("=" * 55)

# Check which provider is configured
client = _build_client()
if client is None:
    print("\n[FAIL] No API key found in .env")
    print("       Copy .env.example to .env and add your key.")
    sys.exit(1)

provider = _detect_provider()
print(f"\n[OK] Provider detected: {provider}")
print("     Sending test request...\n")

# Run a sample report generation
result = generate_clinical_report(
    disease="Diabetes",
    prob_percent=72.5,
    risk_level="High",
    top_factors=[
        {"feature": "Glucose",  "value": 148.0, "shap": 0.312,  "direction": "increases risk"},
        {"feature": "BMI",      "value": 33.6,  "shap": 0.198,  "direction": "increases risk"},
        {"feature": "Age",      "value": 50.0,  "shap": 0.143,  "direction": "increases risk"},
        {"feature": "Insulin",  "value": 0.0,   "shap": -0.089, "direction": "decreases risk"},
        {"feature": "Pregnancies","value": 2.0, "shap": 0.054,  "direction": "increases risk"},
    ],
)

if result["available"]:
    print(f"[OK] Model used : {result['model_used']}")
    print(f"[OK] Provider   : {result['provider']}")
    print("\n── Generated Report ─────────────────────────────────\n")
    print(result["report"])
    print("\n[SUCCESS] API is working correctly.")
else:
    print(f"[FAIL] API call failed: {result['error']}")
    print("\nReport generated by fallback engine:")
    print(result["report"])
